// 18 Strings Empty Check

public class Empt {
    public static void main(String[] args) {

        String s1 = "Dhaka";
        String s2 = "";

        // isEmpty() Method
        // String Empty হলে true এবং Empty না হলে false
        System.out.println("s1" + "=" + s1.isEmpty());

        System.out.println("s2" + "=" + s2.isEmpty());
    }
}