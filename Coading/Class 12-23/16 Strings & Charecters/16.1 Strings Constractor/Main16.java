
public class Main16 {
    public static void main(String[] args) {

        String s = "Computer";

        // charAt() Method
        // Returns character from a specific index

        // Index 0
        char ch = s.charAt(0);
        System.out.println(ch);

        // Index 4
        System.out.println(s.charAt(4));

        // Index 5
        System.out.println(s.charAt(5));

        // Index 6
        System.out.println(s.charAt(6));
    }
}
